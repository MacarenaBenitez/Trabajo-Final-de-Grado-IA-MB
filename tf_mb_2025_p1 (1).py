# ================= Helper para agregar capas =================
def add_gdf_layer(
    gdf_in, name, color, weight=2,
    fill=False, fill_opacity=0.3,
    tooltip_fields=None, popup_fields=None,
    show=True,
    dash_array=None
):
    if gdf_in is None or len(gdf_in) == 0:
        return

    gdf_clean = gdf_in[gdf_in.geometry.notna()].copy()
    gdf_clean = gdf_clean[gdf_clean.geometry.type.isin(
        ["LineString", "MultiLineString", "Polygon", "MultiPolygon"]
    )]
    if gdf_clean.empty:
        return

    gdf_clean = gdf_clean.explode(index_parts=False).reset_index(drop=True)

    def _style(_):
        st = {"color": color, "weight": weight, "fillOpacity": fill_opacity if fill else 0}
        if fill:
            st["fillColor"] = color
        if dash_array:
            st["dashArray"] = dash_array
        return st

    folium.GeoJson(
        gdf_clean.to_crs(4326),
        name=name,
        show=show,
        style_function=_style,
        tooltip=folium.GeoJsonTooltip(fields=tooltip_fields) if tooltip_fields else None,
        popup=folium.GeoJsonPopup(fields=popup_fields) if popup_fields else None
    ).add_to(m)

