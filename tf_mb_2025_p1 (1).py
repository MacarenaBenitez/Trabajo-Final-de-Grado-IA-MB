def clasificar_terciles_por_anio(df_anio):
    s = df_anio["valor_pesos"].astype(float)
    q1 = s.quantile(1/3)
    q2 = s.quantile(2/3)
    def _cat(v):
        if pd.isna(v):
            return None
        if v <= q1: return "Bajo"
        if v <= q2: return "Medio"
        return "Alto"
    return df_anio.assign(clase_valor=s.map(_cat))

