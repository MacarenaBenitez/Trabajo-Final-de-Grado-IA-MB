    out["MES"] = pd.to_numeric(out["MES"], errors="coerce").astype("Int64")
    # Índice a float (aceptando coma como decimal)
    out[col_palmer] = (
        out[col_palmer].astype(str).str.replace(",", ".", regex=False).replace({"": np.nan})
    )
    out[col_palmer] = pd.to_numeric(out[col_palmer], errors="coerce")
    return out

