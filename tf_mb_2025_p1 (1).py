def _session_with_retry(max_retries=3):
    sess = requests.Session()
    retry = Retry(total=max_retries, connect=max_retries, read=max_retries,
                  backoff_factor=1.5, status_forcelist=[502,503,504],
                  allowed_methods=["GET"])
    sess.mount("https://", HTTPAdapter(max_retries=retry))
    return sess

def get_wfs_wgeojson(typename: str, srs=EPSG_POSGAR4, timeout=90, max_retries=3):
    """Descarga WFS completo (sin bbox) como GeoJSON."""
    base = "https://idecor-ws.mapascordoba.gob.ar/geoserver/idecor/ows"
    params = {
        "service": "WFS", "version": "1.1.0", "request": "GetFeature",
        "typeName": typename, "outputFormat": "application/json",
        "srsName": f"EPSG:{srs}",
    }
    sess = _session_with_retry(max_retries)
    headers = {"Accept": "application/json", "Accept-Encoding": "identity"}
    r = sess.get(base, params=params, headers=headers, timeout=timeout)
    r.raise_for_status()
    data = r.json()
    if not data or "features" not in data:
        return gpd.GeoDataFrame(geometry=[], crs=f"EPSG:{srs}")
    return gpd.GeoDataFrame.from_features(data["features"], crs=f"EPSG:{srs}")

def get_wfs_bounded(typename: str, bbox_5348, srs=EPSG_POSGAR4, timeout=90, max_retries=3):
    """Descarga WFS limitado por BBOX (para ahorrar RAM/tiempo)."""
    base = "https://idecor-ws.mapascordoba.gob.ar/geoserver/idecor/ows"
    bbox_txt = ",".join(map(str, [*bbox_5348, f"EPSG:{srs}"]))
    params = {
        "service": "WFS", "version": "1.1.0", "request": "GetFeature",
        "typeName": typename, "outputFormat": "application/json",
        "srsName": f"EPSG:{srs}", "bbox": bbox_txt,
    }
    sess = _session_with_retry(max_retries)
    headers = {"Accept": "application/json", "Accept-Encoding": "identity"}
    r = sess.get(base, params=params, headers=headers, timeout=timeout)
    r.raise_for_status()
    data = r.json()
    if not data or "features" not in data:
        return gpd.GeoDataFrame(geometry=[], crs=f"EPSG:{srs}")
    return gpd.GeoDataFrame.from_features(data["features"], crs=f"EPSG:{srs}")

