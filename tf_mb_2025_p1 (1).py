    candidates.append((
        WFS_WS,
        {
            "service": "WFS",
            "version": "2.0.0",
            "request": "GetFeature",
            "typeNames": type_name,
            "srsName": srs,
            "outputFormat": "application/json",
        },
        "workspace + 2.0.0 + typeNames"
    ))

