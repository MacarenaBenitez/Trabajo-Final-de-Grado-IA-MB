def normalizar_y_filtrar_anio(anio, capa, bbox, union_geom, parcelas_union, radios_union):
    gdf = get_wfs_bounded(capa, bbox, srs=EPSG_POSGAR4)
    if gdf.empty:
        return gpd.GeoDataFrame(columns=["par_idparcela","anio","valor_pesos","geometry"], crs=f"EPSG:{EPSG_POSGAR4}")
    gdf = gpd.overlay(gdf, union_geom, how="intersection", keep_geom_type=False)
    gdf = gdf[gdf.geom_type.isin(["Polygon","MultiPolygon"])].copy()
    posibles = [f"vur_{anio}", "vur_pesos", "valor_pesos"]
    col_valor = next((c for c in posibles if c in gdf.columns), None)
    if col_valor is None:
        return gpd.GeoDataFrame(columns=["par_idparcela","anio","valor_pesos","geometry"], crs=f"EPSG:{EPSG_POSGAR4}")
    gdf = gdf.rename(columns={col_valor:"valor_pesos"})
    gdf["valor_pesos"] = pd.to_numeric(gdf["valor_pesos"], errors="coerce")
    gdf["anio"] = anio
    # join con parcelas (ID)
    sj = gpd.sjoin(gdf[["valor_pesos","anio","geometry"]],
                   parcelas_union[["par_idparcela","geometry"]],
                   how="left", predicate="intersects").drop(columns=["index_right"])
    # fallback centróide
    miss = sj["par_idparcela"].isna()
    if miss.any():
        cent = sj.loc[miss, ["valor_pesos","anio","geometry"]].copy()
        cent["geometry"] = cent.geometry.centroid
        sjc = gpd.sjoin(cent, parcelas_union[["par_idparcela","geometry"]],
                        how="left", predicate="within").drop(columns=["index_right"])
        sj.loc[miss, "par_idparcela"] = sjc["par_idparcela"].values
    sj["par_idparcela"] = sj["par_idparcela"].astype(str)
    # filtrar valor == 1
    sj = sj[sj["valor_pesos"] == 1].copy()
    if sj.empty:
        return sj
    # excluir urbano
    sj = gpd.overlay(sj, radios_union, how="difference", keep_geom_type=False)
    sj = sj[sj.geom_type.isin(["Polygon","MultiPolygon"])].copy()
