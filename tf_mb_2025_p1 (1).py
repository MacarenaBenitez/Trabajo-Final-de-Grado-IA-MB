CANDIDATAS = ["INDICE PALMER", "ÍNDICE PALMER", "INDICE_PALMER", "PALMER", "PSI", "PDSI"]

def detectar_col_palmer(df):
    up = {c.upper(): c for c in df.columns}
    for c in CANDIDATAS:
        if c in up:
            return up[c]
    raise ValueError(f"No encuentro columna del índice Palmer. Probé: {', '.join(CANDIDATAS)}.\nColumnas: {list(df.columns)}")

def asegurar_tipos(df, col_palmer):
    out = df.copy()
    # AÑO y MES a numéricos
