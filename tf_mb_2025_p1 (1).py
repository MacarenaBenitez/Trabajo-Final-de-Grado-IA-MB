def _norm_txt(s):
    import unicodedata
    if pd.isna(s): return ""
    s = unicodedata.normalize("NFD", str(s)).encode("ascii", "ignore").decode()
    return " ".join(s.upper().strip().split())

def ensure_active_geometry(df, prefer=("geometry","geom","geom_ped","wkb_geometry","GEOMETRY")):
    """Asegura que haya columna geométrica activa llamada 'geometry'."""
    if isinstance(df, gpd.GeoDataFrame):
        try:
            _ = df.geometry.name
            if df.geometry.name != "geometry":
                df = df.rename_geometry("geometry")
            return df
        except Exception:
            pass
    # buscar candidata
    for c in prefer:
        if c in df.columns:
            gdf = gpd.GeoDataFrame(df, geometry=c)
            if gdf.geometry.name != "geometry":
                gdf = gdf.rename_geometry("geometry")
            return gdf
    # por dtype geométrico
    geom_cols = [c for c in df.columns if "geometry" in str(df[c].dtype).lower()]
    if geom_cols:
        gdf = gpd.GeoDataFrame(df, geometry=geom_cols[0]).rename_geometry("geometry")
        return gdf
    raise ValueError("No se encontró ninguna columna geométrica en el DataFrame.")

