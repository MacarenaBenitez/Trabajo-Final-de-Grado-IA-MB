def _normalize_text(s: str) -> str:
    if s is None:
        return ""
    s = unicodedata.normalize("NFKD", str(s))
    s = "".join(ch for ch in s if not unicodedata.combining(ch))
    return s.upper().strip()

def get_union_depto(nombre_depto="UNION"):
    objetivo = _normalize_text(nombre_depto)
    gdf_deptos = get_wfs_wgeojson("idecor:departamentos", srs=EPSG_POSGAR4)
    if gdf_deptos.empty:
        raise RuntimeError("No pude descargar 'idecor:departamentos'.")
    cand_cols = [c for c in gdf_deptos.columns if c.lower() in (
        "departamento","nombre","depto","nomdepto","nom_depto","nombre_dep","departamen","dpto"
    )]
    if not cand_cols:
        raise KeyError(f"No encuentro columna de nombre en 'departamentos'. Columnas: {list(gdf_deptos.columns)}")
    col_nombre = cand_cols[0]
    gdf_deptos["_nombre_norm"] = gdf_deptos[col_nombre].apply(_normalize_text)

    sel = gdf_deptos[gdf_deptos["_nombre_norm"] == objetivo]
    if sel.empty:
        sel = gdf_deptos[gdf_deptos["_nombre_norm"].str.contains(objetivo, na=False)]
    if sel.empty:
        sel = gdf_deptos[gdf_deptos["_nombre_norm"].str.startswith(objetivo, na=False)]

    if sel.empty:
        vals = sorted(gdf_deptos["_nombre_norm"].dropna().unique().tolist())
        print("⚠️ No encontré el departamento. Valores disponibles:", vals[:50])
        raise ValueError(f"No encontré el departamento '{nombre_depto}'. Probá con uno de la lista.")

    union = sel.to_crs(EPSG_POSGAR4)[["geometry"]].explode(index_parts=False, ignore_index=True)
    return union

