# ================= Mini-API =================
class IDECORHydroAPI:
    def __init__(self, depto_objetivo: str = DEPTO_OBJETIVO, epsg_out: int = EPSG_POSGAR4):
        self.depto_objetivo = normalizar_txt(depto_objetivo)
        self.epsg_out = epsg_out
        self._depto_gdf_5348 = None  # cache del polígono de depto

    # ---- Departamento (para recortes) ----
    def _get_depto_union(self) -> gpd.GeoDataFrame:
        if self._depto_gdf_5348 is not None:
            return self._depto_gdf_5348

        deptos, _ = _try_first_ok(WFS_WS, TN_DEPARTAMENTO)
        if "nombre" not in deptos.columns:
            raise KeyError(f"No encuentro columna 'nombre' en departamentos: {list(deptos.columns)}")
        deptos["_nombre_norm_"] = deptos["nombre"].apply(normalizar_txt)
        g = deptos[deptos["_nombre_norm_"] == self.depto_objetivo].drop(columns="_nombre_norm_")
        if g.empty:
            raise ValueError(f"No se encontró departamento '{self.depto_objetivo}' en la capa de departamentos.")
        self._depto_gdf_5348 = g.to_crs(self.epsg_out)
        print(f" Departamento '{self.depto_objetivo}' listo para recortes.")
        return self._depto_gdf_5348

    # ---- Descarga genérica + recorte ----
    def _fetch_and_clip(self, url: str, tn_candidates, keep_cols=None) -> gpd.GeoDataFrame:
        gdf, used_tn = _try_first_ok(url, tn_candidates)
        gdf_5348 = gdf.to_crs(self.epsg_out)
        depto_5348 = self._get_depto_union()
        # clip (si falla por geometrías, caemos a sjoin/intersects)
        try:
            clipped = gpd.clip(gdf_5348, depto_5348)
        except Exception:
            clipped = gpd.sjoin(
                gdf_5348,
                depto_5348[["geometry"]],
                how="inner",
                predicate="intersects"
            ).drop(columns="index_right")
        if keep_cols:
            keep = [c for c in keep_cols if c in clipped.columns] + ["geometry"]
            keep = list(dict.fromkeys(keep))  # único y mantener orden
            clipped = clipped[keep]
        print(f"  Recortado '{used_tn}' a '{self.depto_objetivo}': {len(clipped)}")
        return clipped

    # ---- Capas específicas ----
    def acueductos(self) -> gpd.GeoDataFrame:
        return self._fetch_and_clip(WFS_ACUEDUCTOS, TN_ACUEDUCTOS, keep_cols=["id", "nombre"])

    def cursos_agua(self) -> gpd.GeoDataFrame:
        return self._fetch_and_clip(WFS_CURSOS, TN_CURSOS, keep_cols=["id", "nombre", "jerarquia"])

    def embalses(self) -> gpd.GeoDataFrame:
        return self._fetch_and_clip(WFS_EMBALSES, TN_EMBALSES, keep_cols=["id", "nombre", "superficie_ha"])

    def cuerpos_agua_naturales(self) -> gpd.GeoDataFrame:
        return self._fetch_and_clip(
            WFS_CUERPOS,
            TN_CUERPOS,
            keep_cols=["id", "nombre", "tipo", "superficie_ha"]
        )

