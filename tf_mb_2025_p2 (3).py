def graficar_niveles_gemelo_digital(nivel: int, titulo="Niveles de madurez del gemelo digital"):
    """
    Dibuja una barra segmentada por niveles y resalta el nivel alcanzado.
    """
    labels = [
        "Nivel 0\nSin evidencias",
        "Nivel 1\nDescriptivo",
        "Nivel 2\nDiagnóstico /\nDinámico",
        "Nivel 3\nPredictivo\nvalidado",
        "Nivel 4\nBidireccional"
    ]

    colors = ["#d9d9d9", "#9ecae1", "#6baed6", "#3182bd", "#08519c"]
    edge = "#1f1f1f"

    fig, ax = plt.subplots(figsize=(13, 3.6))

    x0, y0 = 0, 0.9
    h = 0.6

    # segmentos
    for i in range(5):
        ax.add_patch(
            Rectangle(
                (x0 + i, y0), 1, h,
                facecolor=colors[i],
                edgecolor=edge,
                linewidth=1.4
            )
        )

    # borde externo
    ax.add_patch(Rectangle((x0, y0), 5, h, fill=False, edgecolor=edge, linewidth=1.6))

    # etiquetas
    for i, lab in enumerate(labels):
        ax.text(
            x0 + i + 0.5,
            y0 - 0.14,
            lab,
            ha="center",
            va="top",
            fontsize=10
        )

    # línea del nivel
    nivel = int(max(0, min(4, nivel)))
    x_linea = x0 + nivel + 0.5

    ax.plot(
        [x_linea, x_linea],
        [y0, y0 + h],
        linestyle="--",
        linewidth=2.4,
        color="red"
    )

    ax.text(
        x_linea,
        y0 + h + 0.16,
        f"Ubicación del prototipo\nNivel {nivel}",
        color="red",
        fontsize=10,
        ha="center",
        va="bottom",
        fontweight="bold"
    )

    # título
    ax.text(
        2.5,
        y0 + h + 0.48,
        titulo,
        ha="center",
        va="bottom",
        fontsize=14,
        fontweight="bold"
    )

    ax.set_xlim(-0.2, 5.2)
    ax.set_ylim(0, 2.1)
    ax.axis("off")
    plt.tight_layout()
    plt.show()


