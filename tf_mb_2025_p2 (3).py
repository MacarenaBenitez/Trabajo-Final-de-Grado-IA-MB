def inferir_nivel(resumen: dict, entradas: dict) -> int:
    """
    Devuelve un nivel 0..4 según la clasificación y criterios del prototipo.
    """

    tipo = str(resumen.get("clasificacion_tipo", "") or "").lower()

    # Nivel 4: bidireccional
    if "bidireccional" in tipo or entradas.get("retroalimentacion_bidireccional", False):
        return 4

    # Nivel 3: predictivo validado
    if (
        ("unidireccional" in tipo and "anal" in tipo)
        or (entradas.get("capacidad_predictiva", False) and entradas.get("informa_decisiones", False))
    ):
        return 3

    # Nivel 2: diagnóstico/dinámico
    if entradas.get("capacidad_predictiva", False) or entradas.get("imita_comportamiento", False):
        return 2

    # Nivel 1: descriptivo
    if entradas.get("imita_estructura", False) and entradas.get("imita_contexto", False):
        return 1

    # Nivel 0: sin evidencias
    return 0


